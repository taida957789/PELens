# ------------------------------------------------------------------ main
def main():
    sig_xml, sigs = signatures()
    files = {
        'settings.xml': settings(), 'indicators.xml': indicators(), 'thresholds.xml': thresholds(),
        'functions.xml': functions(), 'strings.xml': strings(), 'signatures.xml': sig_xml, 'mitre.xml': mitre_xml(),
        'namespaces.xml': namespaces(), 'rich.xml': rich(), 'languages.xml': languages(), 'translations.xml': translations(sigs),
    }
    if errors:
        print('\n'.join(errors), file=sys.stderr)
        sys.exit(1)
    stale = []
    for name, content in files.items():
        path = os.path.join(ROOT, name)
        old = open(path, encoding='utf-8').read() if os.path.exists(path) else None
        if old != content:
            stale.append(name)
            if '--check' not in sys.argv:
                with open(path, 'w', encoding='utf-8', newline='\n') as f:
                    f.write(content)
    if '--check' in sys.argv:
        if stale:
            print('out of date: ' + ', '.join(stale) + ' (run python tools/build_kb.py)', file=sys.stderr)
            sys.exit(1)
        print('kb is up to date')
    else:
        print(f'wrote {len(stale)} file(s): {", ".join(stale) or "none changed"}')


if __name__ == '__main__':
    main()
