"""Build the PELens open knowledge base (kb/*.xml) from the sources in kb/src.

The XML files use pestudio's format so that PELens reads either knowledge base, but every entry
comes from kb/src (written for PELens, see kb/SOURCES.md). Edit the sources, then run:

    python tools/build_kb.py          # write kb/*.xml
    python tools/build_kb.py --check  # fail if kb/*.xml is out of date (CI)
"""
import os
import sys

ROOT = os.path.normpath(os.path.join(os.path.dirname(__file__), '..', 'kb'))
SRC = os.path.join(ROOT, 'src')
HEADER = ('<!--\nPELens open knowledge base - CC0 1.0 (see kb/LICENSE; MITRE ATT&amp;CK names: see kb/SOURCES.md).\n'
          'Generated by tools/build_kb.py from kb/src: edit the sources, not this file.\n-->\n')
errors = []


def rows(name, cols):
    out = []
    with open(os.path.join(SRC, name), encoding='utf-8') as f:
        for n, line in enumerate(f, 1):
            line = line.rstrip('\r\n')
            if not line.strip() or line.startswith('#'):
                continue
            parts = line.split('\t')
            if len(parts) != cols:
                errors.append(f'{name}:{n}: {len(parts)} columns, expected {cols}')
                continue
            out.append([p.strip() for p in parts])
    return out


def esc(s):
    return s.replace('&', '&amp;').replace('<', '&lt;').replace('>', '&gt;').replace('"', '&quot;')


def doc(body):
    return HEADER + '<xml version="1.0" encoding="utf-8">\n' + body + '</xml>\n'


# ------------------------------------------------------------------ shared tables
groups = rows('groups.tsv', 6)
group_ids = {g[0] for g in groups}
mitre = rows('mitre.tsv', 6)
technique_ids = {m[1] for m in mitre if m[0] == 'ti'}
tactic_ids = {m[1] for m in mitre if m[0] == 'ta'}


def gp(value, where):
    if value in ('--', ''):
        return '--'
    if value not in group_ids:
        errors.append(f'{where}: unknown group {value}')
    return value


def ti(value, where):
    if value in ('----', ''):
        return '----'
    if value not in technique_ids:
        errors.append(f'{where}: technique {value} missing from mitre.tsv')
    return value


def flag(value, where):
    if value not in ('0', '1'):
        errors.append(f'{where}: flag must be 0 or 1, got {value!r}')
    return value


# ------------------------------------------------------------------ indicators.xml
def indicators():
    out = ['<indicators>']
    seen = set()
    for i, sev, view, tech, name, detail in rows('indicators.tsv', 6):
        where = f'indicators.tsv {i}'
        if i in seen:
            errors.append(f'{where}: duplicate')
        seen.add(i)
        if sev not in '123':
            errors.append(f'{where}: severity {sev}')
        out.append(f'  <item enable="1" severity="{sev}" id="{i}" type="{view}" ti="{ti(tech, where)}" '
                   f'detail="{esc(detail)}">{esc(name)}</item>')
    out.append('</indicators>')
    return doc('\n'.join(out) + '\n')


# ------------------------------------------------------------------ thresholds.xml
# id: what the engine compares (crates/pe-analysis/src/indicators.rs, strings)
THRESHOLDS = [
    ('002', 2, 32, 1024),    # DOS stub size in bytes (1489 outside the range)
    ('009', 2, 256, -1),     # long string: minimum length (1267)
    ('023', 2, 1995, -1),    # compiler stamp: earliest plausible year
    ('030', 2, -1, 2100),    # compiler stamp: latest plausible year
]


def thresholds():
    body = '\n'.join(f'  <item id="{i}" enable="1" level="{lv}" min="{lo}" max="{hi}"></item>' for i, lv, lo, hi in THRESHOLDS)
    return doc('<thresholds>\n' + body + '\n</thresholds>\n')


# ------------------------------------------------------------------ functions.xml
def functions():
    libs = {}
    for lib, g, fl, desc in rows('libraries.tsv', 4):
        where = f'libraries.tsv {lib}'
        if lib != lib.lower():
            errors.append(f'{where}: library names are lower case')
        if lib in libs:
            errors.append(f'{where}: duplicate')
        libs[lib] = (gp(g, where), flag(fl, where), desc, [])
    seen = set()
    for lib, fct, g, fl, tech, attrs in rows('functions.tsv', 6):
        where = f'functions.tsv {lib}!{fct}'
        if lib not in libs:
            errors.append(f'{where}: library missing from libraries.tsv')
            continue
        if (lib, fct) in seen:
            errors.append(f'{where}: duplicate')
        seen.add((lib, fct))
        extra = ''
        for a in ([] if attrs == '-' else attrs.split(',')):
            a = a.strip()
            if a not in ('ad', 'cb', 'cd', 'un'):
                errors.append(f'{where}: unknown attribute {a}')
            else:
                extra += f' {a}="1"'
        libs[lib][3].append(f'      <fct gp="{gp(g, where)}" flag="{flag(fl, where)}" ti="{ti(tech, where)}"{extra}>{esc(fct)}</fct>')
    out = ['<libs>']
    for lib, (g, fl, desc, fcts) in libs.items():
        out.append(f'  <lib name="{esc(lib)}" flag="{fl}" gp="{g}" desc="{esc(desc)}">')
        out.append('    <fcts>')
        out.extend(fcts)
        out.append('    </fcts>')
        out.append('  </lib>')
    out.append('</libs>')
    return doc('\n'.join(out) + '\n')


# ------------------------------------------------------------------ strings.xml
CATEGORIES = [  # category element, item element, hint id
    ('sids', 'sid', '03'), ('privs', 'priv', '02'), ('agents', 'agent', '06'), ('exts', 'ext', '04'),
    ('regs', 'reg', '01'), ('folders', 'folder', '05'), ('offices', 'office', '07'), ('utils', 'util', '08'),
    ('stubs', 'stub', '09'), ('strings', 'string', None),
]


def strings():
    by_cat = {c[0]: [] for c in CATEGORIES}
    seen = set()
    for cat, value, g, tech, fl, bl in rows('strings.tsv', 6):
        where = f'strings.tsv {cat}:{value}'
        if cat not in by_cat:
            errors.append(f'{where}: unknown category')
            continue
        if (cat, value.lower()) in seen:
            errors.append(f'{where}: duplicate')
        seen.add((cat, value.lower()))
        by_cat[cat].append((value, gp(g, where), ti(tech, where), flag(fl, where), flag(bl, where)))
    out = ['<settings><setting><minimum-size>4</minimum-size><case-sensitive>0</case-sensitive><substring>0</substring></setting></settings>']
    for cat, item, hint in CATEGORIES:
        h = f' hint="{hint}"' if hint else ''
        out.append(f'<{cat}{h}>')
        for value, g, t, fl, bl in by_cat[cat]:
            out.append(f'  <{item} gp="{g}" ti="{t}" flag="{fl}" bl="{bl}">{esc(value)}</{item}>')
        out.append(f'</{cat}>')
    return doc('\n'.join(out) + '\n')


# ------------------------------------------------------------------ signatures.xml
def signatures():
    sigs = {}
    for name, kind, sev, where_, pattern, desc, url in rows('signatures.tsv', 7):
        where = f'signatures.tsv {name}'
        if kind not in ('tool', 'file') or sev not in '1234' or where_ not in ('ep', 'start', 'text'):
            errors.append(f'{where}: bad kind/severity/where')
        s = sigs.setdefault(name, (kind, sev, desc, url, []))
        if s[:4] != (kind, sev, desc, url):
            errors.append(f'{where}: kind/severity/description/url differ between lines')
        s[4].append((where_, pattern))
    out = ['<sigs>']
    for name, (kind, sev, desc, url, pats) in sigs.items():
        u = '' if url == '-' else url
        out.append(f'  <sig name="{esc(name)}" more="{esc(desc)}" flag="1" file="{int(kind == "file")}" '
                   f'tool="{int(kind == "tool")}" severity="{sev}" url="{esc(u)}">')
        for w, p in pats:
            out.append(f'    <pattern ep="{int(w == "ep")}">{esc(p)}</pattern>')
        out.append('  </sig>')
    out.append('</sigs>')
    return doc('\n'.join(out) + '\n'), sigs


# ------------------------------------------------------------------ mitre.xml
def mitre_xml():
    out = ['<mitre url="https://attack.mitre.org">', '  <tactics url="tactics">']
    for kind, i, name, tactic, fl, level in mitre:
        if kind == 'ta':
            out.append(f'    <ta id="{i}" de="">{esc(name)}</ta>')
    out.append('  </tactics>')
    out.append('  <techniques url="techniques">')
    for kind, i, name, tactic, fl, level in mitre:
        if kind == 'ti':
            if tactic not in tactic_ids:
                errors.append(f'mitre.tsv {i}: unknown tactic {tactic}')
            out.append(f'    <ti id="{i}" ta="{tactic}" flag="{fl}" level="{level}" enable="1">{esc(name)}</ti>')
    out.append('  </techniques>')
    out.append('</mitre>')
    return doc('\n'.join(out) + '\n')


# ------------------------------------------------------------------ namespaces.xml
def namespaces():
    kinds = {'system': [], 'custom': []}
    seen = set()
    for kind, ns, g, tech, fl in rows('namespaces.tsv', 5):
        where = f'namespaces.tsv {ns}'
        if kind not in kinds:
            errors.append(f'{where}: kind must be system or custom')
            continue
        if ns in seen:
            errors.append(f'{where}: duplicate')
        seen.add(ns)
        kinds[kind].append(f'    <item flag="{flag(fl, where)}" gp="{gp(g, where)}" ti="{ti(tech, where)}">{esc(ns)}</item>')
    out = ['<nsp>']
    for kind, items in kinds.items():
        out.append(f'  <nsp_{kind} enable="1">')
        out.extend(items)
        out.append(f'  </nsp_{kind}>')
    out.append('</nsp>')
    return doc('\n'.join(out) + '\n')


